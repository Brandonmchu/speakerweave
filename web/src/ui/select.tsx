// Tailwind runs with important:'#root', so a portal that lands on document.body
// escapes every utility we wrote. Resolve to #root instead.
function usePortalContainer(container?: HTMLElement | null) {
  return React.useMemo(() => {
    if (container) return container
    if (typeof document === 'undefined') return undefined
    return document.getElementById('root') ?? document.body
  }, [container])
}

const SelectContent = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Content> & { container?: HTMLElement | null }
>(({ className, children, position = 'popper', container, ...props }, ref) => {
  const resolvedContainer = usePortalContainer(container)

  return (
    <SelectPrimitive.Portal container={resolvedContainer}>
      <SelectPrimitive.Content
        ref={ref}
        className={cn(
          'relative z-50 max-h-[300px] min-w-[8rem] overflow-hidden rounded-md bg-popover text-popover-foreground shadow-raised',
          'data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95',
          'data-[side=bottom]:slide-in-from-top-2 data-[side=top]:slide-in-from-bottom-2',
          position === 'popper' && 'data-[side=bottom]:translate-y-1 data-[side=top]:-translate-y-1',
          className
        )}
        position={position}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          className={cn(
            'p-1 scrollbar-app',
            position === 'popper' && 'w-full min-w-[var(--radix-select-trigger-width)]'
          )}
          style={{ maxHeight: '280px', overflowY: 'auto' }}
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
})
SelectContent.displayName = SelectPrimitive.Content.displayName

